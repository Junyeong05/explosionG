export interface RuleV3 {
  key: string;
  from: AttackCat;
  to: AttackCat;
  title: string;
  name: string;
  /** 공통 규칙에서 나온 문장 (A 의 몸 + B 의 성질) */
  text: string;
  /** 손으로 쓴 새 성질 */
  trait: string;
}

const CATS = ATTACK_CATEGORIES as readonly AttackCat[];

/** 210 규칙 v3 */
export function rulesV3(): RuleV3[] {
  const out: RuleV3[] = [];
  for (const a of CATS) {
    for (const b of CATS) {
      if (a === b) continue;
      const key = `${a}>${b}`;
      const n = N[key];
      if (!n) throw new Error(`v3 이름 없음: ${key}`);
      out.push({ key, from: a, to: b, title: `${CATEGORY_LABEL[a]} + ${CATEGORY_LABEL[b]}`, name: n[0], text: `${DELIVERY[a]}, 그것이 ${BECOME[b]}.`, trait: n[1] });
    }
  }
  return out;
}

/** 몸(A) 갈래가 그것이 B 가 될 때 남기는 제 한 방의 몫 */
export function keepOf(cat: string): number {
  return V3.keepAOf[cat as AttackCat] ?? V3.keepA;
}
