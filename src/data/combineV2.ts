const CATS = ATTACK_CATEGORIES as readonly AttackCat[];

/** 210 규칙 v2 */
export function rulesV2(): RuleV2[] {
  const out: RuleV2[] = [];
  for (const a of CATS) {
    for (const b of CATS) {
      if (a === b) continue;
      const key = `${a}>${b}`;
      const r = T[key];
      if (!r) throw new Error(`v2 규칙 없음: ${key}`);
      out.push({ key, from: a, to: b, title: `${CATEGORY_LABEL[a]} + ${CATEGORY_LABEL[b]}`, name: r[0], text: r[1] + '.' });
    }
  }
  return out;
}

/** 손 입력 모양 (미리보기·검증이 자동으로 누르는 방식) */
export type InputPattern = 'tap' | 'hold' | 'link' | 'tri' | 'path' | 'beat' | 'mash';

const HAND_INPUT: Record<AttackCat, InputPattern> = {
  hand: 'tap',
  gun: 'hold',
  turret: 'hold',
  summon: 'tap',
  magic: 'tri',
  trap: 'link',
  air: 'path',
  charge: 'link',
  sound: 'beat',
  spinner: 'hold',
  field: 'path',
  ray: 'link',
  throw: 'path',
  swarm: 'mash',
  spirit: 'tap',
};

/** 이 짝을 보여 줄 때 누르는 방식 (손이 없으면 null) */
export function inputFor(a: AttackCat, b: AttackCat): InputPattern | null {
  if (a === 'hand') return HAND_INPUT[b];
  if (b === 'hand') return a === 'sound' || a === 'swarm' ? 'hold' : 'tap';
  return null;
}

